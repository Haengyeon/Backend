/**
 * 그 시군구가 지도에서 차지하는 칸 전부.
 *
 * 모르는 코드면 빈 배열이고, 그때는 지도에 아무것도 안 칠한다.
 * 엉뚱한 칸을 칠하는 것보다 낫다.
 */
export function mapCellsOfSigungu(
  region: Region,
  sigunguCode: string | null,
): string[] {
  if (!sigunguCode) return [];
  return SIGUNGU_MAP_CELLS[region]?.[sigunguCode] ?? [];
}

/** 스탬프를 찍을 수 있는 곳인지. 매칭 요청 검증에 쓴다 */
export function isStampableSigungu(
  region: Region,
  sigunguCode: string,
): boolean {
  return mapCellsOfSigungu(region, sigunguCode).length > 0;
}

/**
 * 스탬프 수집 진행률의 분모. 지도 칸 수(250)가 아니라 시군구 수다.
 *
 * 분모를 칸으로 두면 수원시를 골라도 4칸 중 어디가 칠해질지 고를 수 없어
 * 100%가 영영 안 나온다. 고를 수 있는 단위로 세야 달성 가능한 수가 된다.
 */
export const SIGUNGU_TOTAL = Object.values(SIGUNGU_MAP_CELLS).reduce(
  (total, codes) => total + Object.keys(codes).length,
  0,
);
